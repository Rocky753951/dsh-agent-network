test('register, send, receive, and health work over HTTP', async (t) => {
  const server = new AgentNetworkServer({ host: '127.0.0.1', port: 0 });
  await server.start();
  t.after(() => server.stop());
  const base = `http://127.0.0.1:${server.address().port}`;
  const auth = { 'content-type': 'application/json', 'x-agent-network-token': server.localToken };
  const request = (path, options = {}) => fetch(`${base}${path}`, options).then(async (response) => ({ status: response.status, body: await response.json() }));
  const json = (path, body) => request(path, { method: 'POST', headers: auth, body: JSON.stringify(body) });
  const registered = await json('/register', { agentId: 'agent-test', metadata: { role: 'tester' } });
  assert.equal(registered.status, 200);
  assert.equal(registered.body.agentId, 'agent-test');
  const health = await request('/dan/0.1/health');
  assert.equal(health.body.ok, true);
  assert.equal(health.body.agents, 1);
  const rpc = await json('/dan/0.1/rpc', { kind: 'request', protocol: 'dan/0.1', request_id: 'req-1', message_id: 'msg-1', session_id: 'sess-1', sender: 'agent-source', recipient: 'host', sent_at: new Date().toISOString(), ttl_ms: 30000, seq: 1, body: { method: 'ping' } });
  assert.equal(rpc.status, 200);
  assert.equal(rpc.body.result.pong, true);
  const sent = await json('/send', { from: 'agent-source', to: 'agent-test', payload: { text: 'hello' } });
  assert.equal(sent.status, 200);
  assert.equal(sent.body.payload.text, 'hello');
  const received = await request('/receive?agentId=agent-test', { headers: { 'x-agent-network-token': server.localToken } });
  assert.equal(received.body.messages.length, 1);
  assert.equal(received.body.messages[0].from, 'agent-source');
  const drained = await request('/receive?agentId=agent-test', { headers: { 'x-agent-network-token': server.localToken } });
  assert.deepEqual(drained.body.messages, []);
});

test('loopback demo routes require the connector token and reject foreign origins', async (t) => {
  const server = new AgentNetworkServer({ host: '127.0.0.1', port: 0 });
  await server.start();
  t.after(() => server.stop());
  const base = `http://127.0.0.1:${server.address().port}`;
  const unauthenticated = await fetch(`${base}/register`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: '{}' });
  assert.equal(unauthenticated.status, 401);
  assert.equal((await unauthenticated.json()).error.code, 'unauthorized');
  const forgedOrigin = await fetch(`${base}/send`, { method: 'POST', headers: { 'content-type': 'application/json', origin: 'https://evil.example', 'x-agent-network-token': server.localToken }, body: '{"to":"x","payload":{}}' });
  assert.equal(forgedOrigin.status, 403);
  assert.equal((await forgedOrigin.json()).error.code, 'origin_not_allowed');
  const loopbackOrigin = await fetch(`${base}/health`, { headers: { origin: 'http://127.0.0.1:33080' } });
  assert.equal(loopbackOrigin.status, 200);
  assert.equal(loopbackOrigin.headers.get('access-control-allow-origin'), 'http://127.0.0.1:33080');
  const foreignCors = await fetch(`${base}/health`, { headers: { origin: 'https://evil.example' } });
  assert.equal(foreignCors.headers.get('access-control-allow-origin'), null);
});

test('formal RPC route is exact and JSON-only', async (t) => {
  const server = new AgentNetworkServer({ host: '127.0.0.1', port: 0, contract: { nodeId: '55555555-5555-4555-8555-555555555555', hmac: { keyId: 'test-key', keys: { 'test-key': 'test-secret' }, bindings: { 'test-key': '44444444-4444-4444-8444-444444444444' }, required: true } } });
  await server.start();
  t.after(() => server.stop());
  const base = `http://127.0.0.1:${server.address().port}`;
  const envelope = { kind: 'request', protocol: 'dan/0.1', request_id: '11111111-1111-4111-8111-111111111111', message_id: '22222222-2222-4222-8222-222222222222', session_id: '33333333-3333-4333-8333-333333333333', sender: '44444444-4444-4444-8444-444444444444', recipient: '55555555-5555-4555-8555-555555555555', sent_at: new Date().toISOString(), ttl_ms: 30000, seq: 1, method: 'ping', body: {} };
  envelope.auth = { alg: 'HS256', key_id: 'test-key', ts: new Date().toISOString(), nonce: 'MTIzNDU2Nzg5MDEyMzQ1Njc4OTA' };
  envelope.auth.mac = signEnvelope(envelope, 'test-secret');
  const valid = await fetch(`${base}/api/agent-network/v1/rpc`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: canonical(envelope) });
  assert.equal(valid.status, 200);
  const replay = await fetch(`${base}/api/agent-network/v1/rpc`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: canonical(envelope) });
  assert.equal(replay.status, 409);
  assert.equal((await replay.json()).error.code, 'replay_detected');
  const missingAuth = { ...envelope }; delete missingAuth.auth;
  const missingAuthResponse = await fetch(`${base}/api/agent-network/v1/rpc`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: canonical(missingAuth) });
  assert.equal(missingAuthResponse.status, 400);
  const missingAuthBody = await missingAuthResponse.json();
  assert.equal(missingAuthBody.error.code, 'invalid_envelope');
  assert.equal(missingAuthBody.reply_to, envelope.message_id);
  assert.equal(missingAuthBody.ok, false);
  const badTrace = { ...envelope, trace: { trace_id: 'trace', extra: true } };
  const badTraceResponse = await fetch(`${base}/api/agent-network/v1/rpc`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: canonical(badTrace) });
  assert.equal((await badTraceResponse.json()).error.code, 'invalid_envelope');
  const wrongType = await fetch(`${base}/api/agent-network/v1/rpc`, { method: 'POST', headers: { 'content-type': 'text/plain' }, body: canonical(envelope) });
  assert.equal(wrongType.status, 400);
  assert.equal((await wrongType.json()).error.code, 'invalid_content_type');
  const wrongMethod = await fetch(`${base}/api/agent-network/v1/rpc`);
  assert.equal(wrongMethod.status, 405);
  const options = await fetch(`${base}/api/agent-network/v1/rpc`, { method: 'OPTIONS' });
  assert.equal(options.status, 405);
  const empty = await fetch(`${base}/api/agent-network/v1/rpc`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: '' });
  assert.equal(empty.status, 400);
  assert.equal((await empty.json()).error.code, 'invalid_json');
  const oversized = await fetch(`${base}/api/agent-network/v1/rpc`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ data: 'x'.repeat(1_100_000) }) });
  assert.equal(oversized.status, 413);
  assert.equal((await oversized.json()).error.code, 'message_too_large');
  const duplicate = await fetch(`${base}/api/agent-network/v1/rpc`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: '{"kind":"request","kind":"request"}' });
  assert.equal(duplicate.status, 400);
  assert.equal((await duplicate.json()).error.code, 'invalid_json');
  const nestedSameKey = await fetch(`${base}/api/agent-network/v1/rpc`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: canonical({ outer: { key: 1 }, other: { key: 2 } }) });
  assert.equal(nestedSameKey.status, 400);
  assert.equal((await nestedSameKey.json()).error.code, 'invalid_envelope');
  const escapedDuplicate = await fetch(`${base}/api/agent-network/v1/rpc`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: '{"a":1,"\\u0061":2}' });
  assert.equal(escapedDuplicate.status, 400);
  assert.equal((await escapedDuplicate.json()).error.code, 'invalid_json');
  const bom = await fetch(`${base}/api/agent-network/v1/rpc`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: Buffer.concat([Buffer.from([0xef, 0xbb, 0xbf]), Buffer.from('{}')]) });
  assert.equal(bom.status, 400);
  assert.equal((await bom.json()).error.code, 'invalid_json');
  const nonCanonical = await fetch(`${base}/api/agent-network/v1/rpc`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: '{ "a": 1 }' });
  assert.equal(nonCanonical.status, 400);
  assert.equal((await nonCanonical.json()).error.code, 'invalid_json');
  const unknown = await fetch(`${base}/api/agent-network/v1/other`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: '{}' });
  assert.equal(unknown.status, 404);
});

test('formal Host can stop and restart cleanly', async () => {
  const server = new AgentNetworkServer({ host: '127.0.0.1', port: 0 });
  await server.start();
  const firstPort = server.address().port;
  await server.stop();
  assert.equal(server.address(), null);
  await server.start();
  assert.ok(server.address().port > 0);
  assert.equal(typeof firstPort, 'number');
  await server.stop();
});

test('unknown agents are rejected', async (t) => {
  const server = new AgentNetworkServer({ host: '127.0.0.1', port: 0 });
  await server.start();
  t.after(() => server.stop());
  const anonymous = await fetch(`http://127.0.0.1:${server.address().port}/receive?agentId=missing`);
  assert.equal(anonymous.status, 401);
  const response = await fetch(`http://127.0.0.1:${server.address().port}/receive?agentId=missing`, { headers: { 'x-agent-network-token': server.localToken } });
  assert.equal(response.status, 404);
});
